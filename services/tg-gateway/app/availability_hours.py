"""Часы формы занятости: какие интервалы выходят за рабочий день.

Вынесено из `main.py`, потому что там ошибка «0 часов» была замаскирована
конструкцией `int(start or 8)`: полночь — законный час, но `0` ложен, и вместо
неё подставлялись 8 утра. Из-за этого «Весь день» (00–24) считался рабочим
интервалом, а API справедливо отвечал 400 `outside_work_day` — человек видел
pop-up «Не удалось записать» (обращение №34).
"""

WORK_DAY_START = 8          # рабочий день студии: 08:00–23:00
WORK_DAY_END = 24           # граница «до», не включается: 23:00 — последний рабочий час


def outside_work_day(start: int, end: int) -> bool:
    """Интервал выходит за 08–24? None не подставляем: 0 — это полночь."""
    if start is None or end is None:
        return True
    return start < WORK_DAY_START or end > WORK_DAY_END
