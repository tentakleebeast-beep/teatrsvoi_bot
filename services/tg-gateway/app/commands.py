"""Канонические команды чата: один список на подсказки, меню бота и тесты.

Telegram подсвечивает и автодополняет только латинские команды: кириллическая
форма (`/заметка`) приходит обычным текстом и работает лишь потому, что у
обработчика есть алиас (`Command("заметка", "note")`). В интерфейсе она командой
не выглядит — человек читает совет «/заметка …», печатает `/note` и не понимает,
почему подсказка и меню расходятся.

Поэтому у каждой команды одно каноническое имя — латиница; алиасы живут у
обработчиков как совместимость и в подсказки не попадают (решение 05.11.2026).

`COMMANDS` — единственный источник правды:

* `menu_commands()` отдаёт набор для `setMyCommands` (стартует `main.py`);
* сам `COMMANDS` — с ним сверяются подсказки в тесте
  `tests/unit/test_gateway_command_hints.py`.

Добавили команду — допишите её сюда: иначе она не появится в меню, а подсказка
с ней уронит тест.
"""

from __future__ import annotations

import re
from typing import NamedTuple

#: Имя, которое Telegram принимает в меню: строчная латиница, цифры, подчёркивание.
#: Дефис и кириллица отклоняются всем запросом целиком, поэтому такие команды
#: остаются рабочими, но в меню не попадают.
MENU_NAME_RE = re.compile(r"^[a-z0-9_]{1,32}$")


class Command(NamedTuple):
    """Команда чата: каноническое имя без слэша, описание человеку и флаг меню."""

    name: str
    description: str
    in_menu: bool = True


#: Все команды чата. `in_menu=False` — рабочая команда, которой в меню быть не
#: должно: служебная, админская или с именем, которое Telegram в меню не примет.
COMMANDS: tuple[Command, ...] = (
    # --- повседневное: то, что человек делает с телефона ------------------------
    Command("note", "записать заметку одной фразой"),
    Command("notes", "где живут заметки"),
    Command("expense", "записать расход"),
    Command("income", "записать доход"),
    Command("dues", "мои взносы: тариф и учтено ли за месяц"),
    Command("profile", "мой профиль: имя, контакты, короткие имена"),
    Command("busy", "отметить занятость: свободен, занят, до какого часа"),
    Command("week", "обычная неделя: запомнить и заполнить"),
    Command("quiet", "тихие часы: 20:00-08:00 или «выкл»"),
    Command("feedback", "сообщить о проблеме или пожелании"),
    Command("help", "что умею: справка по вашей роли"),
    Command("menu", "главное меню кнопками"),
    Command("start", "начать заново: знакомство и выбор себя", in_menu=False),
    # --- файлы: пока только администратор (П-7, docs/development/92 §9.1) -------
    Command("files", "последние файлы", in_menu=False),
    Command("folders", "папки: общие и личные", in_menu=False),
    Command("mkdir", "создать папку", in_menu=False),
    Command("rename", "переименовать папку", in_menu=False),
    Command("rmfolder", "закрыть папку", in_menu=False),
    Command("order", "порядок файлов в папке", in_menu=False),
    Command("zip", "архив папки", in_menu=False),
    Command("search", "найти файл", in_menu=False),
    Command("tags", "теги файлов", in_menu=False),
    Command("tag", "прицепить теги к файлу", in_menu=False),
    # Дефис в имени: Telegram такое в меню не принимает, поэтому только руками.
    Command("tag-ok", "утвердить тег", in_menu=False),
    Command("access", "открыть доступ к чужому файлу", in_menu=False),
    Command("revoke", "отозвать доступ", in_menu=False),
    # --- служебное --------------------------------------------------------------
    Command("intro", "знакомство: как зовут и как обращаться", in_menu=False),
)


def menu_commands() -> tuple[Command, ...]:
    """Набор для `setMyCommands`: только то, что Telegram примет в меню.

    Фильтр по имени, а не по одному флагу: команда с дефисом (`tag-ok`) в меню
    не проходит, и один такой элемент отклонил бы весь запрос.
    """
    return tuple(item for item in COMMANDS
                 if item.in_menu and MENU_NAME_RE.match(item.name))
