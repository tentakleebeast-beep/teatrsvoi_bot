"""
Маршрутизация свободного текста в gateway.

Вынесено из main.py, потому что порядок правил — это поведение, а поведение
надо проверять тестами без Telegram. Ошибка порядка однажды уже стоила нам
неработающей админ-панели (docs/reports/27 §1.1).

Правила применяются по порядку; первое, которое вернуло «обработал»,
останавливает цепочку. Если ни одно не справилось — текст уходит в n8n-роутер.
"""

from __future__ import annotations

import re

# --- шаблоны ---------------------------------------------------------------

BUDGET_WORDS = r"расход|потрат|оплат|заплат|купил|отдал|приход|поступ|взнос|перевел"
AVAIL_WORDS = r"занят|свобод|могу|не могу|не смогу|удобн|работаю"
ABOUT_ME = (r"^(кто я|кто я такой|кто я такая|мой профиль|мои роли|моя роль|"
            r"кто я в боте)")
LIST_PEOPLE = (r"(список.*(участник|людей|пользовател)|"
               r"кто\s+(зарегистр|в\s+системе|у\s+нас\s+в\s+боте)|"
               r"зарегистрирован|состав\s+(студи|трупп)|"
               r"(все|всех|покажи|дай|выведи).{0,20}(участник|людей|пользовател|трупп))")
HOWTO_Q = r"^(как|где|чем|почему|зачем|можно\s+ли|подскажи|объясни|научи)\b"
MONEY_Q = (r"(сколько\s+(у\s+нас\s+)?(денег|средств|на\s+счет|осталось)|"
           r"какой\s+баланс|баланс\s+студи|сколько\s+потратили|сколько\s+заработали|"
           r"итог\s+месяца|денег\s+на)")
ASSIGN_Q = (r"(назначь|назначить|запланируй|поставь\s+(репетици|показ|тренинг|аренд|встреч))")
SLOTS_Q = (r"(окн[оа]\b|когда\s+(все\s+)?свободн|найди\s+(время|окно)|"
           r"общее\s+время|когда\s+можно\s+собрат|свободные\s+часы)")
SCHEDULE_Q = (r"(расписан|что\s+у\s+меня\s+(сегодня|завтра|послезавтра|на\s+неделе)|"
              r"что\s+(у\s+нас\s+)?(на|в)\s+(неделе|пн|вт|ср|чт|пт|сб|вс|"
              r"понедельник|вторник|сред|четверг|пятниц|суббот|воскрес)|"
              r"план\s+на\s+недел|занятость\s+на\s+недел|кто\s+свободен|какие\s+события)")
# «Где больше всего свободных» — не тип события, а режим поиска (FR-D7).
# Тип по умолчанию (репетиция, docs/architecture/42 §6) сюда подставлять нельзя:
# человеку нужны часы «придёт больше всех», а не окно «все свободны».
# Серверный близнец правила — `subject.MAX_FREE_RE` (services/tool-api).
MAX_FREE_Q = (r"(больше\s+(всех|всего)|максимум\s+свободн|как\s+можно\s+больше\s+(людей|участников)|"
              r"побольше\s+людей|сбор\s+всей)")
# Вопрос о чужой занятости, а не ввод своих данных: «кто сегодня занят» идёт
# к агенту (у него инструмент read_availability), а «занят 28.10 с 10 до 14» —
# по-прежнему ввод формы. Без этого правила AVAIL_WORDS ловил вопрос раньше
# агента, и кэш занятости в бою не срабатывал (возврат ревью A-4, 02.11.2026).
AVAIL_Q = (r"(кто\s+((сегодня|завтра|послезавтра|сейчас)\s+)?(занят|свободен)|"
           r"покажи\s+занятост|занятость\s+на\s+(сегодня|завтра))")
DIGIT_RE = re.compile(r"\d")

# порядок важен: более узкие и более «дешёвые» правила идут раньше
# Ш-52: сначала вопросы о существующем (диалог), потом ввод данных (команда/форма).
# Порядок — поведение: «сколько потратили в октябре» содержит и цифру, и «потрат»,
# но это вопрос, а не черновик траты.
QUESTION_RULES: tuple[str, ...] = ("about_me", "list_people", "howto", "slots",
                                   "money", "schedule", "availability_q")
DATA_INPUT_RULES: tuple[str, ...] = ("availability", "assign", "budget")
RULES: tuple[tuple[str, str], ...] = (
    ("about_me", ABOUT_ME),
    ("list_people", LIST_PEOPLE),
    ("howto", HOWTO_Q),
    ("slots", SLOTS_Q),
    ("money", MONEY_Q),
    ("schedule", SCHEDULE_Q),
    ("availability_q", AVAIL_Q),
    ("availability", AVAIL_WORDS),
    # назначение раньше бюджета: «назначь репетицию в 20» — это не трата 20 ₽
    ("assign", ASSIGN_Q),
    ("budget", BUDGET_WORDS),
)

_COMPILED = tuple((name, re.compile(pattern)) for name, pattern in RULES)


TIME_LIKE = re.compile(r"\bв\s*\d{1,2}(?::\d{2})?\b|\b\d{1,2}:\d{2}\b|\bпосле\s*\d{1,2}\b"
                       r"|\b\d{1,2}\s*-\s*\d{1,2}\b")


def candidates(text: str) -> list[str]:
    """
    Все правила, которые срабатывают на фразе, в порядке применения.

    Наличие цифры включает ветку бюджета («3000» без слов — уже операция), но
    только если это не время и не назначение: «назначь репетицию в 20» — не трата.
    """
    low = (text or "").lower()
    names = [name for name, rx in _COMPILED if rx.search(low)]
    time_like = bool(TIME_LIKE.search(low))
    if (DIGIT_RE.search(low) and "budget" not in names
            and "assign" not in names and not time_like
            and not any(name in names for name in QUESTION_RULES)):
        names.insert(1, "budget")
    # «как записать расход» — инструкция: правила бюджета пробуют, но не берут,
    # и до howto доходит только если суммы нет
    return names



def data_input_kind(text: str) -> str | None:
    """Тип ввода данных, если фраза — это данные, а не вопрос (Ш-52).

    Возвращает availability / assign / budget для первой подходящей ветки ввода.
    Вопрос о существующем возвращает None: им занимается диалог.
    """
    for name in candidates(text):
        if name in QUESTION_RULES:
            return None
        if name in DATA_INPUT_RULES:
            return name
    return None


#: Просьбы-действия: с них начинается задача, а не вопрос («собери окна…»).
TASK_START = re.compile(
    r"^\s*(собери|собрать|поставь|поставить|найди|найти|создай|создать|запиши|записать|"
    r"добавь|добавить|назначь|назначить|подбери|подобрать|проверь|проверить|сделай|"
    r"сделать|организуй|организовать|запланируй|запланировать|перенеси|перенести)\b")


def is_task(text: str) -> bool:
    """Задача или вопрос: от этого зависит рамка агента (6–8 шагов вместо 4).

    Признак — просьба сделать, а не спросить: глагол действия в начале и хотя бы
    два слова после него. «найди в интернете, когда открывается сезон» — задача,
    «какой сегодня день» — вопрос. Недорогой разбор строкой: модель не решает,
    сколько ей шагов, лимит задаёт код.
    """
    clean = " ".join((text or "").split())
    if len(clean.split()) < 3:
        return False
    return bool(TASK_START.match(clean))
