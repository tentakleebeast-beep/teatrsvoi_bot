"""Блок «Поиск окон не для вашей роли» для экрана `/webapp/slots`.

Отдельный модуль, а не ещё десять строк в `misc_slots.py`: у экрана потолок
400 строк (`tests/unit/test_webapp_pages_split.py`), а разметка и помощники
блока живут одним куском и подклеиваются к странице.

Зачем блок нужен. Список людей (`GET /webapp/slots/people`) и сам поиск
(`POST /webapp/slots/find`) закрыты правом `schedule.slots`: оно есть у
организатора и мастера, у труппы его нет (`db/init/008`, `db/init/061`).
До правки экран читал только `body.ok`, поэтому ответ 403 попадал в ветку
сетевой ошибки: «Люди не загрузились. Потяните экран вниз, чтобы попробовать
снова» — и человек тянул экран бесконечно. 403 — это не сеть, а право:
экран говорит, у кого поиск есть и у кого просить права (принципы 91: 8, 9, Б3;
карта t_f802d135, дизайн-ревью экранов 08.11.2026).

Помощники `$`, `make`, `api` живут в общем замыкании CORE, поэтому скрипт
просто конкатенируется к странице.
"""

from __future__ import annotations

# Разметка блока: показывается только при 403, форма поиска в это время скрыта.
DENIED_BODY = """
<section class="ui-section" id="denied" hidden>
  <div class="ui-empty">
    <div class="ui-empty__title">Поиск окон не для вашей роли</div>
    <div class="ui-empty__text" id="denied-text">Поиск окон ведут организатор и мастер.
      Права выдаёт администратор — попросите его открыть поиск, если он нужен вам.</div>
  </div>
</section>
"""

# Скрипт блока: `drawDenied()` прячет форму, `deniedText()` отдаёт тот же текст
# ответом на 403 от самого поиска — формулировка одна, а не две похожие.
DENIED_SCRIPT = r"""
  /* Права `schedule.slots` нет у труппы (db/init/061: право есть у орга и мастера).
     Экран, получивший 403, прячет форму поиска и говорит, у кого поиск есть:
     «Люди не загрузились. Потяните экран вниз» на 403 — это ложный сбой сети,
     человек тянет бесконечно (карта t_f802d135, принципы 91: 8, 9, Б3). */
  function drawDenied() {
    $("denied").hidden = false;
    $("search-form").hidden = true;
  }

  function deniedText() {
    return $("denied-text").textContent.replace(/\s+/g, " ").trim();
  }
"""
