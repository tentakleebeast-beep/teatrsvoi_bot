"""Канонические имена статей бюджета и алиасы к ним (E6-2, docs/development/196 §9).

Имя статьи приходит строкой из трёх мест: из текста чата (`tg-gateway`), из старого
импорта и из формы, где человек мог написать прежнее слово. Если `_ensure_category`
не узнает старое имя, он вставит **вторую** статью — I3 продолжит зеленеть, а доход
разъедется по двум строкам.

Решение — один словарь: имя нормализуется (нижний регистр, без «ё», сжатые пробелы)
и подставляется каноническое до поиска в базе. Других мест, где имя статьи
сравнивается строкой, не заводится.
"""

from __future__ import annotations

import re

#: Каноническое имя статьи аренды помещения — доход студии (V-126).
LEASE_INCOME = "Аренда (доход)"

#: Нормализованное имя → каноническое. «Субаренда» — прежнее имя той же статьи,
#: читается как алиас и не создаёт вторую категорию.
CANONICAL: dict[str, str] = {
    "субаренда": LEASE_INCOME,
    "аренда (доход)": LEASE_INCOME,
}

_SPACES = re.compile(r"\s+")


def normalize(name: str) -> str:
    """Нижний регистр, без «ё», сжатые пробелы, без пробелов по краям."""
    return _SPACES.sub(" ", (name or "").replace("ё", "е").replace("Ё", "Е").strip().lower())


def canonical(name: str) -> str:
    """Каноническое имя статьи: известный алиас заменяется, остальное — как есть.

    Возвращаем исходное (не нормализованное) имя, если алиаса нет: имя статьи в
    базе может быть с заглавными буквами и «ё», и трогать его здесь нельзя.
    """
    if not name:
        return name
    return CANONICAL.get(normalize(name), name.strip())


def is_lease_income(name: str) -> bool:
    """Статья — доход от аренды помещения (`block='sublease'`), а не показ."""
    return normalize(name) in CANONICAL
