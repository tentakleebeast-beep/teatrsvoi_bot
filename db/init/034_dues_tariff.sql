-- 034: тариф взносов в профиле участника (FR-B7, INT-003)
--
-- Решение заказчика 28.10.2026: взнос начисляется ежемесячно по тарифу из профиля;
-- новый тариф действует со следующего месяца, перерасчётов нет. Поэтому тариф —
-- не константа в коде, а пара «сумма + с какого дня действует».
--
-- История изменений тарифа не хранится: перерасчётов нет, а начисление делает
-- планировщик на старте месяца. Если тариф подняли в середине месяца, начисление
-- прошлого месяца задним числом уже не восстановить — это осознанное ограничение.

begin;

alter table participant
  add column if not exists dues_tariff numeric(12,2)
    check (dues_tariff is null or dues_tariff >= 0),
  add column if not exists dues_tariff_from date;

comment on column participant.dues_tariff is
    'месячный тариф взноса, ₽; null — тариф не задан, автоначисления по человеку нет';
comment on column participant.dues_tariff_from is
    'с какого дня действует текущий тариф; null — действует без ограничения срока';

commit;
