-- 057: рассылка — только у администратора (П-6, карта Ш-02, docs/development/92 §2.4).
--
-- Зачем. Решение П-6 (docs/reports/124 §1): действие «Отправить рассылку» остаётся
-- под правом `notify.send`, но выдаётся только админу, организатору — нет. Роль `org`
-- в `008_rbac_capabilities.sql` держала `notify.send`, поэтому в коде рассылка была
-- доступна и организатору: строка «Рассылка» приходила ему из реестра `SECTIONS`
-- (caps `notify.send`), а `POST /webapp/admin/broadcast` отвечал 200. Документы
-- (82 §3.4, 92 §2.4) обещали «по праву», и право по факту было у org — расхождение,
-- которое эта миграция снимает на уровне данных, а не текста.
--
-- Что здесь: снимается связь «роль org → notify.send». Сама возможность остаётся
-- у роли admin; личные выдачи (`participant_capability_override`) не трогаются —
-- точечная выдача админом по-прежнему возможна и пишется в аудит.
--
-- Номер. Максимум по всем ветвям — 055, и он занят дважды: на `main`
-- (`055_agent_observability_cost.sql`) и в невлитой ветке AUD-7 (`t_353c96ef`,
-- `055_participant_role_revoked.sql`). Поэтому беру 057, а 056 занят веткой Ш-11
-- (`056_notification_defaults.sql`, карта `t_06f42b73`) — при слиянии AUD-7 её
-- 055 перенумеровывается в 058, а не в 056: два файла с одним номером роняют
-- `check_registers` (`test_настоящие_миграции_без_дублей_номеров`). Пока Ш-11 не
-- слита, пропуск 056 записан как безопасный в `scripts/arch_drift.py`
-- (`DOCUMENTED_GAPS[56]`); ту запись снимает коммит, вносящий 056.
--
-- Прод. Миграция идемпотентна: повторный выкат ничего не меняет. Применяет владелец
-- отдельной картой деплоя, эта карта на прод не ходит.

begin;

delete from rbac_role_capability
 where role = 'org'
   and capability = 'notify.send';

commit;
