-- 067: черновик опроса с анкетой оргсостава — 46 открытых вопросов.
--
-- Спецификация — docs/development/167-poll-interview-draft.md §3–§4; тексты вопросов —
-- docs/development/161-google-interview-questionnaire.md версия 8, дословно. Миграция
-- тексты не редактирует: правку формулировок делает владелец в конструкторе Mini App.
--
-- Что создаётся: один `poll` со `status='draft'` и 46 строк `poll_question`
-- (`position` 1–46, все `kind='text'`, `required=true`, `free_text=false`,
-- `max_choices=null`). `poll_option`, `poll_audience`, `poll_person`, `poll_run`,
-- `poll_answer`, `poll_viewer` не заполняются: адресатов выбирает владелец на экране,
-- отправка — его действие, миграция никого не приглашает (167 §3 D4).
--
-- Автор — конкретный человек по устойчивому ключу `person_key`, а не литерал `id`
-- (167 §3 D2): `participant.id` на другой базе указывает на другого человека, а на
-- свежей базе из `db/init` участников нет вовсе. Запасное правило — первый действующий
-- администратор (dev/test-базы). Если нет ни того, ни другого, файл ничего не создаёт
-- и печатает notice: накат на пустую базу не падает.
--
-- Идемпотентность (167 §3 D5): два признака в одном `where not exists` — ключ
-- `067_poll_interview_draft` в `migration_marker` (переживает переименование черновика)
-- и совпадение `title` (страховка, если метку потеряли). Вопросы вставляются через CTE
-- от `returning id`: если черновик уже был, CTE пуст. `update` в файле нет вообще,
-- поэтому правки владельца повторный прогон не откатывает. Метка пишется только если
-- черновик в базе есть — иначе на свежей базе она запретила бы создание навсегда.

begin;

with владелец as (
  select coalesce(
           (select id from participant where person_key = 'мамлютов-виктор'),
           (select id from participant where role = 'admin' and status = 'active'
             order by id limit 1)
         ) as id
), черновик as (
  insert into poll (title, intro, status, anonymous, closes_at, created_by)
  select 'Анкета оргсостава — черновик',
         'Как сейчас устроена работа в театре: 46 открытых вопросов, ответы своими словами. '
         'Отвечать можно частями — прогресс сохраняется.',
         'draft', false, null, владелец.id
    from владелец
   where владелец.id is not null
     and not exists (select 1 from poll where title = 'Анкета оргсостава — черновик')
     and not exists (select 1 from migration_marker where key = '067_poll_interview_draft')
  returning id
)
insert into poll_question (poll_id, position, text, kind, required, free_text, max_choices)
select черновик.id, в.position, в.text, 'text', true, false, null
  from черновик
 cross join (values
       (1, 'Расскажи, как выглядит твой обычный день в театре: с чего начинается, что делаешь первым?'),
       (2, 'Как часто ты обращаешься к общим файлам театра и зачем? Что ищешь в них чаще всего?'),
       (3, 'Нужно найти время для репетиции. Проведи меня по шагам: что смотришь сначала, что потом, кому пишешь или звонишь?'),
       (4, 'Что из этого ты решаешь сам, а что кто-то подтверждает за тебя?'),
       (5, 'Что чаще всего идёт не так в расписании и что ты делаешь, когда это случилось?'),
       (6, 'Кто и когда обновляет таблицу занятости? В ней есть колонка «Решение» — она нужна или её можно убрать?'),
       (7, 'Вспомни последнюю аренду: от заявки до оплаты — что и где ты записывал?'),
       (8, 'Если событие в календаре изменил кто-то другой, как ты об этом узнаёшь сейчас и что делаешь? Кого из организаторов бот может считать хозяином такого события?'),
       (9, 'Пять типов событий — аренда [А], спектакль [С], репетиция [Р], тренинг [Т], проект [П] — каким цветом пометить каждый изначально? Назови словами или номером палитры Google Календаря.'),
       (10, 'Что бы ты хотел улучшить в организации театра?'),
       (11, 'Какие есть идеи по развитию театра?'),
       (12, 'Чем бы тебе могла быть полезна автоматизация с помощью ИИ?'),
       (13, 'Проведи меня по бюджету месяца: с чего начинаешь и чем заканчиваешь?'),
       (14, 'Что в листе трогать нельзя, иначе всё поедет, — а что мешает и хочется переделать?'),
       (15, 'Расскажи на примере последней траты: где и как ты её записала? Статью пишешь словами или выбираешь из списка? Есть ли у тебя свой список статей?'),
       (16, 'Как ты понимаешь, сколько осталось на конец месяца?'),
       (17, 'Кто отмечает, что студиец заплатил взнос, и когда ты об этом узнаёшь? Что делать с тем, кто не заплатил: напоминать ему, показывать тебе список, ничего?'),
       (18, 'Как ты считаешь оплату педагогам: из чего складывается сумма и когда ты её считаешь?'),
       (19, 'Где вы публикуете и где лежат материалы для постов — афиши, тексты, фото?'),
       (20, 'Как ты понимаешь, что пост готов к публикации?'),
       (21, 'Что из твоей работы бот мог бы делать за тебя? О каких сроках тебе важно получать напоминание?'),
       (22, 'Что бы ты хотел улучшить в организации театра?'),
       (23, 'Какие есть идеи по развитию театра?'),
       (24, 'Чем бы тебе могла быть полезна автоматизация с помощью ИИ?'),
       (25, 'Расскажи, как проходит твой день с тренингом: что делаешь до него и после?'),
       (26, 'Как ты показываешь, когда занят, а когда свободен?'),
       (27, 'Когда ты открываешь расписание и что в нём ищешь?'),
       (28, 'Что нужно подготовить к тренингу из файлов и музыки? Куда ты складываешь новое?'),
       (29, 'Как ты узнаёшь, сколько тебе заплатят за месяц? Из чего складывается сумма?'),
       (30, 'Что тебе нужно узнать из бота первым делом, когда ты его открываешь?'),
       (31, 'О каких изменениях в расписании тебе важно узнавать сразу, а о каких — не надо?'),
