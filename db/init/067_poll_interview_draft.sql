       (33, 'Что бы ты хотел улучшить в организации театра?'),
       (34, 'Какие есть идеи по развитию театра?'),
       (35, 'Чем бы тебе могла быть полезна автоматизация с помощью ИИ?'),
       (36, 'Как ты узнаёшь, когда у тебя репетиция или тренинг?'),
       (37, 'Где и как ты отмечаешь, что свободен или занят?'),
       (38, 'Что тебе нужно узнать или найти перед репетицией или тренингом? Отличается ли подготовка к одному и к другому?'),
       (39, 'Что чаще всего идёт не так с репетициями и тренингами и что ты делаешь, когда это случилось?'),
       (40, 'Если репетиция или тренинг отменились, как ты об этом узнаёшь и что делаешь дальше?'),
       (41, 'О чём тебе важно получать сообщение от театра, а о чём — не надо? Чем сообщение о тренинге отличается от сообщения о репетиции?'),
       (42, 'Какие файлы театра тебе нужны чаще всего и зачем? К тренингу и к репетиции нужны разные файлы?'),
       (43, 'Что тебе важно знать о репетиции или тренинге, кроме даты и времени? Для репетиции — какой спектакль и что за роль, для тренинга — какая дисциплина и кто ведёт?'),
       (44, 'Что бы ты хотел улучшить в организации театра?'),
       (45, 'Какие есть идеи по развитию театра?'),
       (46, 'Чем бы тебе могла быть полезна автоматизация с помощью ИИ?')
       ) as в(position, text);

insert into migration_marker (key, note)
select '067_poll_interview_draft', 'черновик анкеты оргсостава: 46 вопросов'
 where exists (select 1 from poll where title = 'Анкета оргсостава — черновик')
on conflict (key) do nothing;

do $$
begin
  if not exists (select 1 from poll where title = 'Анкета оргсостава — черновик') then
    raise notice '067: владельца и действующего администратора нет — черновик не создан';
  end if;
end $$;

commit;
