-- 062: «Файлы студии» — по праву `files.access`, у студийца его нет (V-039 (в), Б3).
--
-- Зачем. Решение владельца V-039 (в) от 08.11.2026 (docs/reports/74-questions.md):
-- раздел «Файлы студии» видят admin, org и master. Экран и данные были закрыты
-- `admin.panel`, и до этой правки `files.access` нигде не спрашивался: он «лежал на
-- будущее» (docs/development/86 §3.5, docs/architecture/140 §6.2) и был выдан в
-- `008_rbac_capabilities.sql` четырём ролям, включая troupe.
--
-- Открыть экран по `files.access` без этой миграции нельзя: у студийца право есть,
-- и он получил бы раздел, который по решению ему не положен. Поэтому связь
-- «роль troupe → files.access» снимается здесь, на уровне данных, а не прячется в
-- коде. Следствие для студийца — честный отказ словами на экране (принцип Б3),
-- а не пустой список и не молчание.
--
-- Кого не трогаем: admin, org и master сохраняют `files.access` (008 и 061);
-- личные выдачи (`participant_capability_override`) остаются как есть — точечное
-- разрешение админа по-прежнему возможно и пишется в аудит.
--
-- Номер. Максимум в `main` и во всех ветках на 08.11.2026 — 061
-- (`061_master_role.sql`), 059 остаётся задокументированным пропуском
-- (`scripts/arch_drift.py`, `DOCUMENTED_GAPS[59]`). Беру 062: следующий свободный.
--
-- Прод. Миграция идемпотентна: повторный выкат ничего не меняет. Применяет владелец
-- отдельной картой деплоя, эта карта на прод не ходит.

begin;

delete from rbac_role_capability
 where role = 'troupe'
   and capability = 'files.access';

commit;
