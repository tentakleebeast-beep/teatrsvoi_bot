-- 20261105: ремонт переноса бюджета в dev-базу (карта t_03cc04e9).
--
-- Что случилось. При сборке новой dev-базы схему подняли из `db/init` начисто, а данные
-- перенесли копированием: `budget_tx` и `participant` совпадают со старой базой построчно
-- (проверено `diff` выгрузок), но словари собирались заново, и суррогатные ключи
-- разъехались:
--   * `budget_period` не перенесли вовсе — 0 строк вместо 5. `v_period_totals` строится
--     от `budget_period`, поэтому отдавал пустоту, а I1 падал на «балансе» без периодов;
--   * `category` собрана из `003_categories_v2.sql`/`015_categories_seed.sql` с новыми
--     `id`. В старой базе тот же справочник жил на других номерах (1–5, 23–38, 125, 126),
--     поэтому 26 строк `budget_tx` после переноса ссылались на чужую категорию
--     (id 5: «Взносы студийцев» стала «Расходники и хозтовары»), а 69 — на несуществующую.
--
-- Про механизм. Сам дамп-источник целостен: `pg_restore` в чистую базу проходит с кодом 0,
-- кладёт 95 строк `budget_tx`, и все 7 FK на `budget_tx` в восстановленной базе имеют
-- `convalidated = t`. Значит, битые ссылки появились не при восстановлении дампа, а при
-- копировании строк в новую базу, где словари уже были собраны заново с другими `id`.
-- С работающим FK такая вставка невозможна (ограничение отвергает строку), поэтому
-- перенос шёл с обходом проверок ссылочной целостности — в реконструкции того же среза
-- он воспроизводится только через `session_replication_role = replica`. На состояние
-- ограничений это не повлияло: в текущей dev-базе все 7 FK на `budget_tx` по-прежнему
-- `convalidated = t`, то есть ограничения проверены и работают.
--
-- Что делает скрипт. Только то, что потеряно при переносе, и ничего про суммы:
--   1. возвращает 5 строк `budget_period` в том виде, в каком они были в источнике
--      (`~/.hermes/cache/scratch/dev-db-before-wave-20261105.dump`);
--   2. возвращает 5 постановок (`project`), на id которых ссылаются операции;
--   3. переносит указатели `budget_tx.category_id` на категорию с тем же именем
--      в действующем справочнике (соответствие снято со старой базы), при необходимости
--      возвращая «Донат» и «Подарок», на которые ссылались операции и которые знает
--      разбор свободного текста (`services/tg-gateway/app/parsers.py`).
--
-- Суммы, даты, типы, блоки и участники не меняются: правятся только потерянные ключи.
-- Скрипт одноразовый, поэтому защищён меткой в `migration_marker` (как 016): повторный
-- накат после ремонта не «переедет» по уже исправленным id.
--
--   docker exec -i svoi-postgres psql -U svoi -d svoi -v ON_ERROR_STOP=1 -f - \
--     < db/repair/20261105_budget_transfer.sql

begin;

-- Защита от повторного наката. После ремонта номера 1–5 заняты настоящими категориями
-- («Тренинги и занятия» и соседние), и второй прогон разложил бы их по старому
-- соответствию — то есть испортил бы уже исправленные строки. Поэтому весь блок
-- выполняется только при отсутствии метки.
select exists (select 1 from migration_marker where key = '20261105_budget_transfer') as applied \gset

\if :applied
  \echo 'ремонт уже применён — пропуск'
\else

-- 1. Справочник периодов: ровно те строки, что были в источнике.
insert into budget_period (period, status, opened_at, quality)
values ('2026-07', 'open', '2026-07-01', 'draft'),
       ('2026-08', 'open', '2026-08-01', 'draft'),
       ('2026-09', 'open', '2026-09-01', 'clean'),
       ('2026-10', 'open', '2026-10-01', 'clean'),
       ('2026-12', 'open', '2026-12-01', 'draft')
on conflict (period) do nothing;

-- 2. Справочник постановок: операции ссылаются на id 1, 2, 3, 5, 6, а таблица пуста —
--    то же расхождение словаря, но здесь id не пересекаются с новыми (таблица пустая),
--    поэтому строки возвращаются с исходными номерами и `budget_tx` править не нужно.
insert into project (id, name, kind, status, created_at) values
  (1, 'Бунин',           'show', 'active', '2026-10-25 15:25:49.44196+00'),
  (2, 'Пурга',           'show', 'active', '2026-10-25 15:25:49.44196+00'),
  (3, 'Жизнь насекомых', 'show', 'active', '2026-10-25 15:25:49.44196+00'),
  (5, 'Чёрная пурга',    'show', 'active', '2026-10-26 22:52:09.781734+00'),
  (6, 'И всё же...',     'show', 'active', '2026-10-26 22:52:09.781734+00')
on conflict do nothing;
select setval('project_id_seq', (select max(id) from project), true);

-- 3. Категории, которые были в источнике и на которые ссылаются операции, но которых
--    нет в заново собранном справочнике.
insert into category (name, direction) values
  ('Донат', 'income'),
  ('Подарок', 'income')
on conflict (name) do nothing;

-- 4. Указатели операций: старый id → имя в источнике → id действующего справочника.
with mapping (old_id, name) as (values
  (1,   'Аренда помещения'),
  (2,   'Коммунальные платежи'),
  (3,   'Ремонт и содержание'),
  (4,   'Фото/видео'),
  (5,   'Взносы студийцев'),
  (23,  'Расходники и хозтовары'),
  (24,  'Реквизит и костюмы'),
  (25,  'Курсы'),
  (27,  'Субаренда'),
  (28,  'Тренинги и занятия'),
  (29,  'Гонорары и доли'),
  (30,  'Закупки к спектаклям'),
  (31,  'Реклама и полиграфия'),
  (33,  'Продажа билетов'),
  (37,  'Возвраты'),
  (38,  'Прочее'),
  (125, 'Донат'),
  (126, 'Подарок')
)
update budget_tx t
   set category_id = c.id
  from mapping m
  join category c on c.name = m.name
 where t.category_id = m.old_id
   and t.category_id is distinct from c.id;

insert into migration_marker (key, note)
values ('20261105_budget_transfer',
        'dev: возвращены 5 периодов и указатели категорий после переноса (t_03cc04e9)')
on conflict (key) do nothing;

\endif

commit;

-- Постпроверка: расхождений быть не должно ни в одной строке.
select 'периодов' as факт, count(*)::text as значение from budget_period
union all select 'постановок', count(*)::text from project
union all select 'операций без категории', count(*)::text
  from budget_tx t left join category c on c.id = t.category_id where c.id is null
union all select 'операций с чужой категорией (тип не совпал)', count(*)::text
  from budget_tx t join category c on c.id = t.category_id
 where c.direction in ('income','expense') and c.direction <> t.tx_type
union all select 'операций без постановки', count(*)::text
  from budget_tx t left join project p on p.id = t.project_id
 where t.project_id is not null and p.id is null;
