"""Разбор метки типа в заголовке события (docs/development/190 §3.2, I-3, I-4).

Обоснование: FR-D3, `docs/development/190` §8 (I-3, I-4): тип узнаётся по маркеру
`svoi_kind`, затем по метке `[X]` в начале `summary`, иначе событие «без типа».
Классификация по словам запрещена: «Аренда зала» без метки — не аренда.
"""

from __future__ import annotations

import pytest
from app.calendar_sync import event_label, plain_title

TITLES = {"rental": "Аренда", "show": "Спектакль", "rehearsal": "Репетиция",
          "training": "Тренинг"}


@pytest.mark.parametrize("summary,letter", [
    ("[С] Жизнь насекомых", "С"),
    ("[С]Жизнь насекомых", "С"),          # без пробела после метки
    ("  [Р] Чёрная пурга", "Р"),          # метка не в самом начале строки
    ("[Я] Неизвестная буква", "Я"),        # буква разбирается, тип — нет
    ("Жизнь насекомых", None),             # метки нет
    ("", None),
    (None, None),
])
def test_метка_в_начале_заголовка(summary, letter) -> None:
    """Метка снимается одна: `[X]` — ведущий маркер, а не любое вхождение."""
    assert event_label(summary) == letter


def test_двойная_метка_снимается_одна() -> None:
    """I-3: снимается один ведущий маркер, второй остаётся частью названия."""
    assert event_label("[С][Р] Название") == "С"
    assert plain_title("[С][Р] Название") == "[Р] Название"


@pytest.mark.parametrize("summary,title", [
    ("[С] Жизнь насекомых", "Жизнь насекомых"),
    ("[С]Жизнь насекомых", "Жизнь насекомых"),
    ("Спектакль - Жизнь насекомых", "Жизнь насекомых"),
    ("Репетиция — Чёрная пурга", "Чёрная пурга"),
    ("Аренда зала", "Аренда зала"),        # без метки слово типа не снимается
    ("", ""),
])
def test_название_без_метки_и_старого_префикса(summary, title) -> None:
    """Старый формат «Тип - Название» тоже снимается: у 446 событий он ещё живёт."""
    assert plain_title(summary, TITLES) == title


def test_без_словаря_снимается_только_метка() -> None:
    """Названия типов приходят из настройки: без словаря старый префикс не угадывается."""
    assert plain_title("Спектакль - Жизнь насекомых") == "Спектакль - Жизнь насекомых"
    assert plain_title("[С] Жизнь насекомых") == "Жизнь насекомых"
