"""
Ключ участника: «иванов-виктор», а не «иванов» и не «дарья васильева».

Ключ — человекочитаемый идентификатор и одновременно имя файла личных настроек.
Значит: строчные буквы, ё → е, никаких пробелов, скобок и знаков препинания.

Правила и требования раздела: docs/architecture/10-data-model-v2.md.
"""

from __future__ import annotations

import pytest
from app.person_key import is_valid, make_key

CASES = [
    ("Иванов Виктор", "иванов-виктор"),
    ("Тарасова Алёна", "тарасова-алена"),
    ("Олег Викторович", "олег-викторович"),
    ("Попова Света", "попова-света"),
    ("  Смирнова   Дарья  ", "смирнова-дарья"),
    ("Иванов Виктор (дубль)", "иванов-виктор"),
    ("Васильева-Смирнова Дарья", "васильева-смирнова-дарья"),
    ("Пётр Ёлкин", "петр-елкин"),
    ("Фомина Арина 2", "фомина-арина-2"),
]


@pytest.mark.parametrize("name,expected", CASES)
def test_ключ_из_полного_имени(name: str, expected: str) -> None:
    assert make_key(name) == expected


def test_ключ_не_содержит_пробелов_и_скобок() -> None:
    """Пробел в ключе ломает обращение к файлу личных настроек."""
    key = make_key("Иванов Виктор (дубль)")
    assert " " not in key and "(" not in key


def test_пустое_имя_даёт_пустой_ключ() -> None:
    """Пустой ключ лучше выдуманного: регистрация сама потребует имя."""
    assert make_key("") == "" and make_key("   ") == ""


def test_готовый_ключ_считается_валидным() -> None:
    assert is_valid("иванов-виктор")
    assert not is_valid("иванов виктор")
